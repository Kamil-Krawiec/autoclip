// Run against the disposable worker-disabled backend and synthetic precise-job fixture.
const assert = require('node:assert/strict')
const { chromium } = require(process.env.AUTOCLIP_PLAYWRIGHT_MODULE || 'playwright')
const baseURL = process.env.AUTOCLIP_TEST_URL || 'http://127.0.0.1:19879'

async function main() {
  const browser = await chromium.launch({ headless: true })
  try {
    const page = await browser.newPage({ baseURL, viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/jobs/precise-job/clips/precise-clip')
    await page.getByRole('button', { name: /^Slice 1:/ }).waitFor()
    await page.getByLabel('Video thumbnails').waitFor({ timeout: 30000 })
    await page.getByLabel('Audio waveform').waitFor()
    await page.getByLabel('Timeline time ruler').waitFor()
    const initialTrack = await page.getByRole('group', { name: 'Framing slices' }).evaluate(el => ({ width: el.getBoundingClientRect().width, parent: el.closest('[aria-label=\"Per-slice framing editor\"]').getBoundingClientRect().width }))
    assert.ok(initialTrack.width > initialTrack.parent * 0.6, 'short clips should use the available timeline width')
    const zoom = page.getByLabel('Timeline zoom')
    await zoom.fill('4')
    const trackSize = await page.getByRole('group', { name: 'Framing slices' }).evaluate(el => ({ width: el.getBoundingClientRect().width, viewport: el.parentElement.clientWidth }))
    assert.ok(trackSize.width > trackSize.viewport * 3)
    await zoom.fill('1')
    const video = page.locator('video').first()
    await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2)
    await page.locator('body').click({ position: { x: 2, y: 2 } })
    await page.keyboard.press('Space')
    await page.waitForFunction(() => !document.querySelector('video').paused)
    await page.keyboard.press('Space')
    await page.waitForFunction(() => document.querySelector('video').paused)
    await video.evaluate(element => { element.currentTime = 3; element.dispatchEvent(new Event('timeupdate')) })
    await page.getByRole('button', { name: /^Split slice at playhead/ }).click()
    await page.getByRole('button', { name: /^Slice 2:/ }).waitFor()
    // A mouse click on Split returns focus to the player shortcut.
    await page.keyboard.press('Space')
    await page.waitForFunction(() => !document.querySelector('video').paused)
    await page.keyboard.press('Space')
    await page.waitForFunction(() => document.querySelector('video').paused)
    // A keyboard-focused button retains its native Space activation.
    const framingTab = page.getByRole('button', { name: 'Framing', exact: true })
    await framingTab.focus()
    await page.keyboard.press('Space')
    assert.equal(await framingTab.getAttribute('aria-pressed'), 'true')
    assert.equal(await video.evaluate(element => element.paused), true)

    await page.getByRole('button', { name: /^Slice 1:/ }).click({ position: { x: 10, y: 20 } })
    await page.getByRole('button', { name: 'Remove section', exact: true }).click()
    await page.getByLabel('Removed section', { exact: true }).waitFor()
    await video.evaluate(element => { element.currentTime = 0 })
    await page.locator('body').click({ position: { x: 2, y: 2 } })
    await page.keyboard.press('Space')
    await page.waitForFunction(() => document.querySelector('video').currentTime >= 3)
    await page.keyboard.press('Space')
    let clip = await (await page.request.get('/api/clips/precise-clip')).json()
    assert.equal(clip.removed_ranges.length, 1)
    await page.reload()
    await page.getByLabel('Removed section', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Export this clip' }).click()
    await page.getByRole('link', { name: /9:16/ }).first().waitFor({ timeout: 120000 })
    clip = await (await page.request.get('/api/clips/precise-clip')).json()
    assert.equal(clip.exports.length, 1)
    await page.getByRole('button', { name: /^Restore 00:/ }).click()
    await page.getByLabel('Removed section', { exact: true }).waitFor({ state: 'hidden' })
    clip = await (await page.request.get('/api/clips/precise-clip')).json()
    assert.deepEqual(clip.removed_ranges, [])
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ passed: true, split: true, removed: true, reloaded: true, export: true, restored: true }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
